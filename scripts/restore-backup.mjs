#!/usr/bin/env node
// Turns a weekly backup JSON file (see worker/src/backup.ts) into a reviewable
// .sql file for restoring library-db. Deliberately does NOT execute anything
// itself — restoring a backup means wiping and replacing every row in these
// tables, and that's not something a script should do unattended. You review
// the generated SQL, then run it yourself.
//
// Usage:
//   1. Download a backup from R2 (see README's Backups section for how to list them):
//        npx wrangler r2 object get library-backups/backups/library-db-2026-08-09-....json \
//          --file=backup.json --remote
//   2. Generate the restore SQL:
//        node scripts/restore-backup.mjs backup.json restore.sql
//   3. Read restore.sql. When you're sure, run it against D1:
//        npx wrangler d1 execute library-db --remote --file=restore.sql
//
// Restoring against local dev instead: drop --remote from step 3.

import { readFileSync, writeFileSync } from "node:fs";

const [, , inputPath, outputPath] = process.argv;
if (!inputPath) {
  console.error("Usage: node scripts/restore-backup.mjs <backup.json> [output.sql]");
  process.exit(1);
}
const outPath = outputPath ?? inputPath.replace(/\.json$/, "") + ".sql";

const backup = JSON.parse(readFileSync(inputPath, "utf-8"));

// Restore order matters for foreign keys: users first, then things that
// reference users, then wishlist_items last (references wishlists).
const RESTORE_ORDER = ["users", "wishlists", "books", "wishlist_items"];

function sqlLiteral(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "1" : "0";
  return `'${String(value).replace(/'/g, "''")}'`;
}

const lines = [
  "-- Generated by scripts/restore-backup.mjs from " + inputPath,
  "-- Backup created at: " + (backup.createdAt ?? "unknown"),
  "-- WARNING: this DELETEs all existing rows in the tables below before restoring.",
  "BEGIN TRANSACTION;",
];

for (const table of RESTORE_ORDER) {
  const rows = backup.tables?.[table];
  if (!rows) continue;
  lines.push(`\n-- ${table} (${rows.length} row${rows.length === 1 ? "" : "s"})`);
  lines.push(`DELETE FROM ${table};`);
  for (const row of rows) {
    const columns = Object.keys(row);
    const values = columns.map((col) => sqlLiteral(row[col]));
    lines.push(`INSERT INTO ${table} (${columns.join(", ")}) VALUES (${values.join(", ")});`);
  }
}

lines.push("\nCOMMIT;");

writeFileSync(outPath, lines.join("\n") + "\n");
console.log(`Wrote ${outPath} (${RESTORE_ORDER.filter((t) => backup.tables?.[t]).length} tables).`);
console.log("Review it, then run:");
console.log(`  npx wrangler d1 execute library-db --remote --file=${outPath}`);
